function setLang(lang, persist){
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key]) el.innerHTML = dict[key][lang];
  });
  document.documentElement.lang = lang;
  document.getElementById('btnNl').classList.toggle('active', lang==='nl');
  document.getElementById('btnEn').classList.toggle('active', lang==='en');
  if(persist !== false){
    try{ localStorage.setItem('meander1-lang', lang); }catch(e){}
  }
}
document.getElementById('btnNl').addEventListener('click', ()=>setLang('nl'));
document.getElementById('btnEn').addEventListener('click', ()=>setLang('en'));

// restore saved language on page load (defaults to nl)
(function(){
  let saved = 'nl';
  try{ saved = localStorage.getItem('meander1-lang') || 'nl'; }catch(e){}
  if(saved === 'en') setLang('en', false);
})();

// paaltje form -> real submission via Formspree
// SETUP (eenmalig, 5 minuten):
// 1. Ga naar https://formspree.io en maak een gratis account aan met paaltje@meander1.nl
// 2. Maak een nieuw formulier aan, Formspree geeft je een endpoint als "https://formspree.io/f/xxxxxxxx"
// 3. Plak die xxxxxxxx-code hieronder in plaats van "YOUR_FORM_ID"
// 4. Formspree stuurt de eerste aanvraag ter bevestiging - klik die mail open om het formulier te activeren
const FORMSPREE_ENDPOINT = 'https://formspree.io/f/xoeagwod';

const paaltjeForm = document.getElementById('paaltjeForm');
if(paaltjeForm){
  const statusEl = document.getElementById('pf-status');
  const submitBtn = document.getElementById('pf-submit');
  const statusText = {
    sending:{nl:'Bezig met versturen…', en:'Sending…'},
    success:{nl:'Verstuurd! Je krijgt een bevestiging per e-mail.', en:'Sent! You will receive a confirmation by email.'},
    error:{nl:'Versturen mislukt. Probeer het nog eens, of mail rechtstreeks naar paaltje@meander1.nl.', en:'Sending failed. Please try again, or email paaltje@meander1.nl directly.'},
    notConfigured:{nl:'Formulier nog niet actief — mail voorlopig naar paaltje@meander1.nl.', en:'Form not active yet — for now, email paaltje@meander1.nl directly.'}
  };
  const currentLang = () => document.documentElement.lang === 'en' ? 'en' : 'nl';

  paaltjeForm.addEventListener('submit', async function(e){
    e.preventDefault();

    if(FORMSPREE_ENDPOINT.includes('YOUR_FORM_ID')){
      statusEl.textContent = statusText.notConfigured[currentLang()];
      return;
    }

    submitBtn.disabled = true;
    statusEl.textContent = statusText.sending[currentLang()];

    try{
      const formData = new FormData(paaltjeForm);
      const res = await fetch(FORMSPREE_ENDPOINT, {
        method: 'POST',
        body: formData,
        headers: { 'Accept': 'application/json' }
      });
      if(res.ok){
        statusEl.textContent = statusText.success[currentLang()];
        paaltjeForm.reset();
      } else {
        statusEl.textContent = statusText.error[currentLang()];
      }
    } catch(err){
      statusEl.textContent = statusText.error[currentLang()];
    } finally {
      submitBtn.disabled = false;
    }
  });
}

// mobile nav
const mobileToggle = document.getElementById('mobileToggle');
const navLinks = document.getElementById('navLinks');
mobileToggle.addEventListener('click', ()=>{
  navLinks.classList.toggle('open');
  document.body.classList.toggle('nav-open', navLinks.classList.contains('open'));
});
navLinks.querySelectorAll('a').forEach(a=>a.addEventListener('click', ()=>{
  navLinks.classList.remove('open');
  document.body.classList.remove('nav-open');
}));

// highlight the current page in the nav
(function(){
  let current = location.pathname.split('/').pop();
  if(current === '' ) current = 'index.html';
  navLinks.querySelectorAll('a').forEach(a=>{
    const href = a.getAttribute('href');
    if(href === current) a.classList.add('active');
  });
})();

// reveal on scroll
const io = new IntersectionObserver(entries=>{
  entries.forEach(e=>{ if(e.isIntersecting){ e.target.classList.add('in'); io.unobserve(e.target); } });
}, {threshold:0.15});
document.querySelectorAll('.reveal').forEach(el=>io.observe(el));
